const fs = require('fs');
const path = require('path');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync(path.join(__dirname, '../static/app.js'), 'utf8');
const context = {settings:{hideOffline:false},stationView:new (require('../static/presence.js').PresenceView)(),data: {stations: [
  {mac:'01:00:5e:00:00:fb'}, {mac:'33:33:00:00:00:fb'},
  {mac:'ff:ff:ff:ff:ff:ff'}, {mac:'da:aa:bb:cc:dd:ee'}, {mac:'bad'}
]}};
vm.createContext(context);
vm.runInContext(source.match(/function validStations\(\)\{[^\n]+/)[0],context);
vm.runInContext(source.match(/function knownStations\(\)\{[^\n]+/)[0], context);
assert.equal(vm.runInContext('knownStations().length', context), 1);
vm.runInContext(source.match(/const esc=[^\n]+/)[0], context);
assert.equal(vm.runInContext('esc("<script>\\\"&")', context), '&lt;script&gt;&quot;&amp;');
console.log('PASS: multicast exclusion; SSID HTML escaping');
const {PresenceView}=require('../static/presence.js');
const view=new PresenceView();
const first=[{bssid:'a',rssi:-80,online:true},{bssid:'b',rssi:-40,online:true}];
assert.deepEqual(view.visible(first,true,a=>a.bssid).map(a=>a.bssid),['a','b']);
assert.deepEqual(view.visible([{...first[1],rssi:-90},{...first[0],rssi:-10}],true,a=>a.bssid).map(a=>a.bssid),['a','b']);
const gone=[{...first[0],online:false},first[1]];
assert.deepEqual(view.visible(gone,true,a=>a.bssid).map(a=>a.bssid),['b']);
assert.deepEqual(view.visible(gone,false,a=>a.bssid).map(a=>a.bssid),['a','b']);
assert.deepEqual(view.visible(first,true,a=>a.bssid).map(a=>a.bssid),['a','b']);
console.log('PASS: stable rows; hide/show round absence; return restores original position');
const {commandMatches,compileHelp}=require('../static/completion.js');
const catalog=compileHelp(['help','recon wifi|ble|status|stop','led -s <hex color>/-p <rainbow>','list -a','list -s','info [-a <index>]','remoteid <scan/list/track/clear> [index]','ssid -a [-g <count>/-n <name>]','select -a/-s/-c <index (comma separated)>/-f "equals <String> or contains <String>"','add -c -b <mac> -ap <ap_index>']);
const matches=s=>commandMatches(s,s.length,catalog);
assert.deepEqual(matches('re').map(x=>x.path),['recon','remoteid']);
assert.equal(matches('recon')[0].insert,'recon ');assert.deepEqual(matches(''),[]);
assert.deepEqual(commandMatches('',0,catalog,true).map(x=>x.path),[...catalog.keys()].sort());
assert.deepEqual(matches('RE').map(x=>x.path),['recon','remoteid']);
assert.deepEqual(matches('unknown'),[]);
assert.deepEqual(matches('recon ').map(x=>x.path),['recon ble','recon status','recon stop','recon wifi']);
assert.equal(matches('recon w')[0].insert,'recon wifi ');
assert.deepEqual(matches('led ').map(x=>x.path),['led -p','led -s']);
assert.equal(matches('led -s ')[0].syntax,'<hex color>');assert.equal(matches('led -s ')[0].insert,null);
assert.deepEqual(matches('list ').map(x=>x.path),['list -a','list -s']);
assert.equal(matches('info -a ')[0].syntax,'<index>');
assert.deepEqual(matches('remoteid ').map(x=>x.path),['remoteid clear','remoteid list','remoteid scan','remoteid track']);
assert.deepEqual(matches('ssid -a ').map(x=>x.path),['ssid -a -g','ssid -a -n']);
assert.equal(matches('ssid -a -g ')[0].syntax,'<count>');
assert.equal(matches('select -a ')[0].syntax,'<index (comma separated)>');
assert.equal(matches('add -c -b aa:bb:cc:dd:ee:ff ')[0].insert,'add -c -b aa:bb:cc:dd:ee:ff -ap ');
assert.deepEqual(commandMatches('recon wifi',3,catalog),[]);
console.log('PASS: first-word popup and explicit empty catalog; hierarchical subcommands/flags; syntax-only placeholders; later options');

